def pe(text: str) -> str:
    """Replace plain emojis with <tg-emoji> tags."""
    if not text:
        return text
    holders = []
    result  = text
    for i, (emoji, doc_id) in enumerate(PREMIUM_EMOJI_IDS.items()):
        ph = f"\x00PE{i:03d}\x00"
        holders.append((ph, doc_id, emoji))
        result = result.replace(emoji, ph)
    for ph, doc_id, emoji in holders:
        result = result.replace(ph, f'<tg-emoji emoji-id="{doc_id}">{emoji}</tg-emoji>')
    return result


def _btn_icon_id(text: str):
    """Return custom-emoji ID for a button's leading emoji, or None."""
    for emoji_char, doc_id in BUTTON_CUSTOM_EMOJIS.items():
        if emoji_char in text:
            return doc_id
    return None


_BTN_EMOJI_STRIP = None  # populated lazily below


def _clean_btn_text(text: str) -> str:
    global _BTN_EMOJI_STRIP
    if _BTN_EMOJI_STRIP is None:
        import re
        _BTN_EMOJI_STRIP = re.compile(
            r"^(?:" + "|".join(
                __import__("re").escape(e) for e in BUTTON_CUSTOM_EMOJIS
            ) + r")\s*"
        )
    return _BTN_EMOJI_STRIP.sub("", text)
