def pe(text):
    """Convert plain emoji to Telegram premium <tg-emoji> markup."""
    if not text:
        return text
    holders = []
    result = text
    for i, (emoji, doc_id) in enumerate(PREMIUM_EMOJI_IDS.items()):
        ph = "\x00PE{:03d}\x00".format(i)
        holders.append((ph, doc_id, emoji))
        result = result.replace(emoji, ph)
    for ph, doc_id, emoji in holders:
        result = result.replace(
            ph,
            '<tg-emoji emoji-id="{}">{}</tg-emoji>'.format(doc_id, emoji),
        )
    return result
